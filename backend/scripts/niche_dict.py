# 非首项命中的最低占比线（首项命中不受此限制）
SECOND_MIN_RATIO = 0.30


def niche_of(items):
    """items = [(构成项名, 占比|None)]（调用方已按占比降序）→ (细分名, 命中依据) | (None, None)。

    首项命中即归属；非首项需占比 ≥ SECOND_MIN_RATIO。多关键词同词根（如"农药中间体"
    含"农药"）不影响——同一规则内的命中取该规则名。
    """
    for i, (name, ratio) in enumerate(items):
        low = (name or "").lower()
        if not low:
            continue
        for niche, kws in NICHE_RULES:
            for kw in kws:
                if kw in low and (i == 0 or (ratio is not None and ratio >= SECOND_MIN_RATIO)):
                    pct = f"@{ratio * 100:.1f}%" if ratio is not None else ""
                    return niche, f"dict:{kw}{pct}"
    return None, None
